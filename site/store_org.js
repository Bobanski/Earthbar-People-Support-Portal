// Case locations are free-ish text (directory store names); match on a
// normalized key (lowercase alphanumerics) so punctuation/spacing variants
// still hit. Unmatched stores bucket under "Other" in the filters.
const norm = s => (s == null ? "" : String(s)).toLowerCase().replace(/[^a-z0-9]/g, "");
const BY_NORM = Object.fromEntries(Object.entries(STORE_ORG).map(([k, v]) => [norm(k), v]));
// Known naming drift between the app's `directory` table and the Store
// Directory. Keep aliases explicit and source-controlled so a naming drift
// cannot silently place a known store under "Other". Normalized keys.
const NORM_ALIASES = {
  earthbarburbank: "eqburbank",
  eqcolumbuscircle: "eqcolumbuscir",
  eqdarienct: "eqdarien",
};
export const storeOrg = name => {
  const k = norm(name);
  return BY_NORM[NORM_ALIASES[k] || k] || null;
};
